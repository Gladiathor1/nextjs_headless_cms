import { Fragment } from 'react'
import Head from 'next/head'
import HeaderMenu from '../components/HeaderMenu'
import styles from '../styles/last_time.module.css'
import React, { useState } from 'react';
import parse from "html-react-parser";

export async function getStaticProps() {
    // Call an external API endpoint to get posts.
    // You can use any data fetching library
    const res = await fetch('https://deliver.kontent.ai/d126e552-2eb3-0059-2e1a-e44dc4b9c001/items/last_time_page')
    const posts = await res.json()
  
    // By returning { props: { posts } }, the Home component
    // will receive `posts` as a prop at build time
    return {
      props: {
        posts,
      },
    }
}

export default function Last_time({ posts }) {
    const [count, setCount] = useState(0);
    function handleClick(e) {
        if(count==0){
            setCount(1)
        }
        else{
            setCount(0)
        }
      }
    return(
        <Fragment>
            <Head>
                <title>Menu</title>
                <meta name="description" content="Generated by create next app" />
                <link rel="icon" href="/favicon.ico" />
            </Head>
            <HeaderMenu
            active="3"
            />

            <div  data-kontent-item-id="4a1f2373-b804-4153-98ea-0b691eb5106f" data-kontent-element-codename="lasttime_page_content" className={styles.main_container}>
                <div className={styles.left_section}>
                    <div className={styles.text_container}>

                    
                        <div data-kontent-element-codename="heading" className={styles.heading}>{posts.modular_content.lasttime_page_content.elements.heading.value}</div>

                        <div data-kontent-element-codename="body_text" className={styles.text}>
                        {parse(posts.modular_content.lasttime_page_content.elements.body_text.value)}
                        </div>

                    </div>
                    <div className={styles.dot +" "+ `${count == "1" ? styles.active : ''}`}>
                        <div onClick={handleClick} className={styles.outer_circle}>
                            <div className={styles.inner_circle}>

                            </div>
                        </div>
                        <div className={styles.dot_content}>
                            <div data-kontent-element-codename="special_text">{posts.modular_content.lasttime_page_content.elements.special_text.value}</div>
                        </div>
                    </div>


                </div>
                <div data-kontent-element-codename="background_image" style={ {background: `url(${posts.modular_content.lasttime_page_content.elements.background_image.value[0].url}) center/cover no-repeat`}} className={styles.right_section}>

                </div>

            </div>


        </Fragment>
    )
}